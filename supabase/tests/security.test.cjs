const { makeDb, as, check, summary } = require('./harness.cjs')
const { ids, seed } = require('./seed.cjs')
// Every migration, in filename order (add new ones here as they're written)
const MIGS = require('fs').readdirSync(require('path').join(__dirname, '..', 'migrations')).filter(f => f.endsWith('.sql')).sort()
const tomorrow = '(current_date + 1)'

async function part1() {
  const db = await makeDb(MIGS)
  await seed(db)
  const adminA = { uid: ids.adminA }, staffA = { uid: ids.staffA }, adminB = { uid: ids.adminB }, sup = { uid: ids.sup }

  console.log('RLS isolation')
  check('anon cannot read clinics', (await as(db, 'anon', 'select * from clinics')).rows.length === 0)
  check('anon cannot read patients', (await as(db, 'anon', 'select * from patients')).rows.length === 0)
  check('anon cannot insert patients', !!(await as(db, 'anon', `insert into patients(clinic_id,full_name,contact_number) values ('${ids.clinicA}','x','123456')`)).error)
  let r = await as(db, adminA, 'select clinic_id from patients')
  check('admin A sees only clinic A patients', r.rows.length === 1 && r.rows[0].clinic_id === ids.clinicA)
  r = await as(db, adminA, `insert into patients(clinic_id,full_name,contact_number) values ('${ids.clinicB}','x','123456')`)
  check('admin A cannot insert patient into clinic B', !!r.error)
  r = await as(db, adminA, 'select id from clinics')
  check('admin A sees only own clinic', r.rows.length === 1)
  r = await as(db, sup, 'select id from clinics')
  check('super admin sees all clinics', r.rows.length === 2)

  console.log('privilege escalation')
  r = await as(db, staffA, `update profiles set role='super_admin' where id='${ids.staffA}'`)
  check('staff cannot make self super_admin', /Cannot change role/.test(r.error || ''), r.error)
  r = await as(db, staffA, `update profiles set clinic_id='${ids.clinicB}' where id='${ids.staffA}'`)
  check('staff cannot move self to clinic B', /Cannot change clinic/.test(r.error || ''), r.error)
  r = await as(db, adminA, `update profiles set clinic_id=null where id='${ids.staffA}'`)
  check('admin cannot detach staff by direct update', !!r.error)
  r = await as(db, staffA, `update profiles set full_name='New Name' where id='${ids.staffA}'`)
  check('staff can edit own full_name', !r.error, r.error)
  r = await as(db, adminA, `update profiles set branch_id=null where id='${ids.staffA}'`)
  check('admin can set staff branch', !r.error, r.error)

  console.log('remove_staff')
  r = await as(db, adminA, `select remove_staff('${ids.staffB}')`)
  check('admin A cannot remove clinic B staff', !!r.error, r.error)
  r = await as(db, adminA, `select remove_staff('${ids.adminA}')`)
  check('admin cannot remove self', /yourself/.test(r.error || ''), r.error)
  r = await as(db, staffA, `select remove_staff('${ids.docA}')`)
  check('staff cannot remove anyone', !!r.error, r.error)
  r = await as(db, 'anon', `select remove_staff('${ids.staffA}')`)
  check('anon cannot call remove_staff', !!r.error)
  r = await as(db, adminA, `select remove_staff('${ids.staffA}')`)
  check('admin can remove staff of own clinic', !r.error, r.error)
  check('removed staff has no clinic', (await db.query(`select clinic_id from profiles where id='${ids.staffA}'`)).rows[0].clinic_id === null)
  await db.query(`update profiles set clinic_id='${ids.clinicA}' where id='${ids.staffA}'`)

  console.log('billing columns')
  r = await as(db, adminA, `update clinics set plan='premium' where id='${ids.clinicA}'`)
  check('admin cannot change clinic plan', /billing/.test(r.error || ''), r.error)
  r = await as(db, adminA, `update clinics set is_trial=true, status='suspended' where id='${ids.clinicA}'`)
  check('admin cannot change is_trial/status', !!r.error)
  r = await as(db, adminA, `update clinics set name='Renamed' where id='${ids.clinicA}'`)
  check('admin can rename clinic', !r.error, r.error)
  await as(db, staffA, `update clinics set name='Hacked' where id='${ids.clinicA}'`)
  check('staff cannot rename clinic', (await db.query(`select name from clinics where id='${ids.clinicA}'`)).rows[0].name === 'Renamed')
  r = await as(db, sup, `update clinics set plan='premium' where id='${ids.clinicA}'`)
  check('super admin can change plan', !r.error, r.error)
  await db.query(`update clinics set plan='pro' where id='${ids.clinicA}'`)

  console.log('subscriptions')
  r = await as(db, adminA, `insert into subscriptions(clinic_id,plan,status,payment_link_id,reference_number,amount,billing_date,next_billing_date) values ('${ids.clinicA}','premium','active','x','y',1,now(),now())`)
  check('admin cannot insert subscription', !!r.error, r.error)
  await db.query(`insert into subscriptions(clinic_id,plan,status,payment_link_id,reference_number,amount,billing_date,next_billing_date) values ('${ids.clinicA}','pro','pending','x','y',1,now(),now())`)
  r = await as(db, adminA, `update subscriptions set status='active'`)
  check('admin cannot activate subscription', !!r.error, r.error)
  check('admin can read own subscriptions', (await as(db, adminA, 'select id from subscriptions')).rows.length === 1)
  check('admin B cannot read clinic A subscriptions', (await as(db, adminB, 'select id from subscriptions')).rows.length === 0)

  console.log('create_clinic')
  r = await as(db, 'anon', `select create_clinic('Anon Clinic')`)
  check('anon cannot call create_clinic', !!r.error)
  r = await as(db, { uid: ids.fresh }, `select (create_clinic('  Fresh Dental!! Clinic ', 'f@x.com')).slug as slug`)
  check('create_clinic works + slug', !r.error && r.rows[0].slug === 'fresh-dental-clinic', JSON.stringify(r))
  const prof = (await db.query(`select role, clinic_id from profiles where id='${ids.fresh}'`)).rows[0]
  check('creator is admin of new clinic', prof && prof.role === 'admin' && prof.clinic_id)
  const subs = (await db.query(`select plan,status from subscriptions where clinic_id='${prof.clinic_id}'`)).rows
  check('trial premium subscription created', subs.length === 1 && subs[0].plan === 'premium' && subs[0].status === 'active')
  r = await as(db, { uid: ids.fresh }, `select create_clinic('Second')`)
  check('cannot create second clinic', /already belongs/.test(r.error || ''), r.error)

  console.log('public booking RPCs')
  r = await as(db, 'anon', `select get_public_clinic('clinic-a') as c`)
  check('get_public_clinic returns clinic w/ branding+settings', r.rows[0] && r.rows[0].c && r.rows[0].c.clinic_branding && r.rows[0].c.clinic_settings)
  check('public clinic hides email', r.rows[0].c.email === null)
  r = await as(db, 'anon', `select * from get_public_doctors('${ids.clinicA}')`)
  check('public doctors lists doctors only', r.rows.length === 1 && r.rows[0].full_name === 'Doc A')
  r = await as(db, 'anon', `select book_public_appointment('${ids.clinicA}', null, 'New Patient', '09990000', 'p@x.com', ${tomorrow}, '10:00', null, 'cat', 'svc', 'n') as id`)
  check('anon can book appointment', !r.error && r.rows[0].id, r.error)
  const pat = (await db.query(`select email from patients where contact_number='09990000'`)).rows
  check('patient created with email', pat.length === 1 && pat[0].email === 'p@x.com')
  r = await as(db, 'anon', `select book_public_appointment('${ids.clinicA}', null, 'New Patient', '09990000', null, ${tomorrow}, '11:00', null, null, null, null) as id`)
  check('rebook reuses existing patient', !r.error && (await db.query(`select 1 from patients where contact_number='09990000'`)).rows.length === 1, r.error)
  check('past date rejected', !!(await as(db, 'anon', `select book_public_appointment('${ids.clinicA}', null, 'Xy', '09990000', null, current_date - 1, null, null, null, null, null)`)).error)
  check('bad branch rejected', !!(await as(db, 'anon', `select book_public_appointment('${ids.clinicA}', '${ids.clinicB}', 'Xy', '09980000', null, ${tomorrow}, null, null, null, null, null)`)).error)
  check('non-doctor rejected as doctor', !!(await as(db, 'anon', `select book_public_appointment('${ids.clinicA}', null, 'Xy', '09980000', null, ${tomorrow}, null, '${ids.staffA}', null, null, null)`)).error)
  check('other clinic doctor rejected', !!(await as(db, 'anon', `select book_public_appointment('${ids.clinicB}', null, 'Xy', '09970000', null, ${tomorrow}, null, '${ids.docA}', null, null, null)`)).error)
  await db.query(`insert into clinic_monthly_usage(clinic_id,new_patients_count) values ('${ids.clinicB}',100) on conflict (clinic_id) do update set new_patients_count=100`)
  r = await as(db, 'anon', `select book_public_appointment('${ids.clinicB}', null, 'Limit Test', '09960000', null, ${tomorrow}, null, null, null, null, null)`)
  check('starter monthly limit enforced for public booking', /not accepting new patients/.test(r.error || ''), r.error)
  await db.query(`update clinics set status='suspended' where id='${ids.clinicB}'`)
  check('suspended clinic hidden', (await as(db, 'anon', `select get_public_clinic('clinic-b') as c`)).rows[0].c === null)
  await db.query(`update clinics set status='active' where id='${ids.clinicB}'`)

  console.log('service role')
  r = await as(db, 'service', `update profiles set role='doctor' where id='${ids.staffA}'`)
  check('service_role can change roles (edge functions)', !r.error, r.error)
  await db.query(`update profiles set role='staff' where id='${ids.staffA}'`)
}

