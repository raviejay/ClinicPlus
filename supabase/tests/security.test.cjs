  check('pro cannot use hybrid booking', !!r.error)
  r = await as(db, adminA, `update clinic_settings set booking_mode='doctor_selection' where clinic_id='${ids.clinicA}'`)
  check('pro can use doctor_selection', !r.error, r.error)
  r = await as(db, { uid: ids.sup }, `update clinic_settings set multi_branch_enabled=true where clinic_id='${ids.clinicB}'`)
  check('super admin bypasses gates', !r.error, r.error)
