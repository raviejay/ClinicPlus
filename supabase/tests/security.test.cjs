  check('per-IP limit (10/hour) blocks booking', /Too many booking attempts/.test(r.error || ''), r.error)
  await db.query(`select set_config('request.headers','',false)`)

  console.log('read-only (expired trial)')
  await db.query(`update clinics set is_trial=true, trial_ends_at = now() - interval '1 day' where id='${ids.clinicA}'`)
